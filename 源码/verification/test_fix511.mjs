import assert from 'node:assert/strict';
import {readFileSync} from 'node:fs';
globalThis.window={addEventListener(){},dispatchEvent(){}};
globalThis.document={getElementById(){return null;}};
globalThis.localStorage={getItem(){return null;}};
const {toKorr}=await import('../Parser/ErCore/web/m3d/korr-adapter.js');
const {aimDirection,aimOf,PosePresenter,blendPose,scenePosition,splitSurfaceIndices}=await import('../Parser/ErCore/web/m3d/gateway-pose.js?v=5.1.1-1');
const supplied=JSON.parse(readFileSync(new URL('../../验证/reported-state.json',import.meta.url),'utf8'));
const characters=supplied.entities.filter(e=>['player','mate','unknown'].includes(e.kind));
const view=toKorr(supplied,{ai:0});
assert.deepEqual(view.players.map(e=>e.key),characters.map(e=>e.key),'AI visibility must not delete player-class bots');
for(const e of view.players)assert.deepEqual([e.x,e.y,e.z],characters.find(c=>c.key===e.key).world);
const withBox=toKorr({entities:[{kind:'box',is_bot:true,key:'box',name:'盒',world:[1,2,3]},{kind:'ai',key:'ai',world:[4,5,6]}]});
assert.equal(withBox.ais.length,1);assert.equal(withBox.items.length,1);
const near=(a,b)=>a.every((v,i)=>Math.abs(v-b[i])<1e-8);
assert(near(aimDirection(90,30),[0,-Math.sqrt(3)/2,.5]));
assert(near(aimDirection(0,-30),[Math.sqrt(3)/2,0,-.5]));
assert.equal(aimOf({self_aim_yaw:90,self_aim_age_ms:1,self_yaw:0}).yaw,90);
assert.equal(aimOf({self_aim_yaw:90,self_aim_age_ms:999,self_yaw:0}).yaw,0);
const h=x=>({key:'h',kind:'player',name:'名字',world:[x,0,0],yaw:x,hp:100});
const snap=(x,extra={})=>({session:1,epoch:1,flow:'f',self:[0,0,0],self_yaw:0,replay:{position:x,paused:false},entities:[h(x)],...extra});
const presenter=new PosePresenter();presenter.push(snap(0),0);presenter.push(snap(100),50);
assert.equal(presenter.sample(75).entities[0].world[0],50);
presenter.push(snap(100),76);
assert.equal(presenter.sample(80).entities[0].world[0],60,'duplicate snapshots must not reset interpolation');
presenter.push(snap(200),80);
assert.equal(presenter.sample(80).entities[0].world[0],60,'new input preserves displayed continuity');
assert(presenter.sample(90).entities[0].world[0]>=60);
presenter.push(snap(20),100);assert.equal(presenter.sample(100).entities[0].world[0],20,'backward seek snaps');
presenter.push(snap(200,{epoch:2}),120);assert.equal(presenter.sample(120).entities[0].world[0],200,'new epoch snaps');
assert.equal(blendPose(h(0),{...h(100),name:'另一个人'},.5).world[0],100,'reused actor slot cannot interpolate different people');
presenter.push(snap(250,{replay:null}),200);assert.equal(presenter.sample(200).entities[0].world[0],250,'live coordinate uses current snapshot');
const a=new Float32Array([0,0,0,10,0,0,0,10,0, 0,0,0,0,10,0,0,0,10]);
const partition=splitSurfaceIndices(a,new Uint32Array([3,4,5,0,1,2]));
assert.equal(partition.horizontal,3);assert.equal(partition.vertical,3);
assert.deepEqual(Array.from(partition.indices),[0,1,2,3,4,5],'all wall and floor triangles retained');
assert.deepEqual(splitSurfaceIndices(a).indices,partition.indices,'nonindexed geometry supported');
assert.equal(toKorr({entities:[{key:'bot-box',kind:'box',is_bot:true,world:[0,0,0]}]},{aibox:0}).items.length,0);
